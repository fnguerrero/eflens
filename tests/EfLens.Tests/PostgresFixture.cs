using System.Runtime.CompilerServices;
using Npgsql;
using Testcontainers.PostgreSql;

namespace EfLens.Tests;

/// <summary>
/// One PostgreSQL container for every PostgreSQL test, with the same shop schema as the SQL Server tests, quoted
/// the way EF Core creates it ("Customers", not customers). Skipped locally without Docker, required in CI.
/// </summary>
public sealed class PostgresFixture : IAsyncLifetime
{
    private const string Image = "postgres:17-alpine";

    private PostgreSqlContainer? _container;

    public string ConnectionString { get; private set; } = "";

    public string? SkipReason { get; private set; }

    public async ValueTask InitializeAsync()
    {
        try
        {
            _container = new PostgreSqlBuilder(Image).Build();
            await _container.StartAsync();
        }
        catch (Exception ex) when (Environment.GetEnvironmentVariable("EFLENS_REQUIRE_DOCKER") != "1")
        {
            SkipReason = $"PostgreSQL container unavailable (is Docker running?): {ex.GetType().Name}";
            return;
        }

        ConnectionString = _container.GetConnectionString();

        await using var db = new NpgsqlConnection(ConnectionString);
        await db.OpenAsync();
        string[] statements =
        [
            "CREATE SCHEMA sales",
            """
            CREATE TABLE public."Customers" (
                "Id" integer GENERATED BY DEFAULT AS IDENTITY CONSTRAINT "PK_Customers" PRIMARY KEY,
                "Name" varchar(100) NOT NULL,
                "Email" varchar(200) NULL CONSTRAINT "UQ_Customers_Email" UNIQUE,
                "Notes" text NULL)
            """,
            """
            CREATE TABLE sales."Orders" (
                "Id" integer NOT NULL CONSTRAINT "PK_Orders" PRIMARY KEY,
                "CustomerId" integer NOT NULL CONSTRAINT "FK_Orders_Customers" REFERENCES public."Customers"("Id") ON DELETE CASCADE,
                "Total" numeric(10,2) NOT NULL DEFAULT 0,
                "PlacedAt" timestamp(3) NOT NULL)
            """,
            """CREATE INDEX "IX_Orders_CustomerId" ON sales."Orders" ("CustomerId")""",
            """
            CREATE TABLE sales."OrderLines" (
                "OrderId" integer NOT NULL,
                "LineNumber" integer NOT NULL,
                "Product" varchar(50) NOT NULL,
                CONSTRAINT "PK_OrderLines" PRIMARY KEY ("OrderId", "LineNumber"),
                CONSTRAINT "FK_OrderLines_Orders" FOREIGN KEY ("OrderId") REFERENCES sales."Orders"("Id"))
            """,
            """CREATE TABLE public."Audit" ("Id" integer NOT NULL)""",
            """CREATE TABLE sales."Audit" ("Id" integer NOT NULL)""",
            """CREATE VIEW public."CustomerTotals" AS SELECT "CustomerId", SUM("Total") AS "Total" FROM sales."Orders" GROUP BY "CustomerId" """,
            """INSERT INTO public."Customers" ("Name", "Email") VALUES ('Ada', 'ada@example.com'), ('Grace', NULL)""",
            """INSERT INTO sales."Orders" VALUES (1, 1, 10.50, '2026-01-01T10:00:00'), (2, 1, 5.00, '2026-01-02T11:30:00')""",
            // A history table outside the default schema, as with HasDefaultSchema / MigrationsHistoryTable(schema).
            "CREATE SCHEMA ef",
            """CREATE TABLE ef."__EFMigrationsHistory" ("MigrationId" varchar(150) PRIMARY KEY, "ProductVersion" varchar(32) NOT NULL)""",
            """INSERT INTO ef."__EFMigrationsHistory" VALUES ('002_AddOrderStatus', '10.0.15'), ('001_InitialCreate', '10.0.15')""",
        ];
        foreach (var sql in statements)
        {
            await using var command = new NpgsqlCommand(sql, db);
            await command.ExecuteNonQueryAsync();
        }
    }

    public async ValueTask DisposeAsync()
    {
        if (_container is not null)
            await _container.DisposeAsync();
    }
}

[CollectionDefinition(Name)]
public sealed class PostgresCollection : ICollectionFixture<PostgresFixture>
{
    public const string Name = "PostgreSQL";
}

/// <summary>EfLens runs Npgsql in raw mode; the switch must be set before the fixture's first command too.</summary>
internal static class TestNpgsqlRawMode
{
    [ModuleInitializer]
    internal static void Enable() => AppContext.SetSwitch("Npgsql.EnableSqlRewriting", false);
}
